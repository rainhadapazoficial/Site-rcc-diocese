-- Create prayer_requests table
CREATE TABLE IF NOT EXISTS prayer_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT,
  message TEXT NOT NULL
);

-- Create posts table
CREATE TABLE IF NOT EXISTS posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  title TEXT NOT NULL,
  excerpt TEXT,
  content TEXT,
  image TEXT,
  category TEXT,
  author TEXT
);

-- Create groups table
CREATE TABLE IF NOT EXISTS groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  nome TEXT NOT NULL,
  dia TEXT NOT NULL,
  local TEXT NOT NULL,
  cidade TEXT NOT NULL,
  geolocalizacao TEXT,
  coordenador TEXT,
  coordenador_foto_url TEXT,
  mandato_id BIGINT REFERENCES conselho_mandatos(id),
  whatsapp TEXT,
  site TEXT,
  facebook TEXT,
  instagram TEXT,
  slug TEXT,
  imagem TEXT,
  descricao TEXT
);

-- Create group_coordinator_history table
CREATE TABLE IF NOT EXISTS group_coordinator_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  group_id BIGINT REFERENCES groups(id) ON DELETE CASCADE,
  nome TEXT NOT NULL,
  gestao TEXT NOT NULL,
  foto_url TEXT,
  mandato_id BIGINT REFERENCES conselho_mandatos(id),
  ordem INTEGER DEFAULT 0
);

-- Create events table
CREATE TABLE IF NOT EXISTS events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  title TEXT NOT NULL,
  description TEXT,
  date TEXT,
  time TEXT,
  location TEXT,
  category TEXT
);

-- Create podcasts table
CREATE TABLE IF NOT EXISTS podcasts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  title TEXT NOT NULL,
  description TEXT,
  spotify_url TEXT,
  youtube_url TEXT,
  category TEXT
);

-- Create gallery table
CREATE TABLE IF NOT EXISTS gallery (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  title TEXT,
  image_url TEXT NOT NULL,
  category TEXT,
  event_date DATE
);

